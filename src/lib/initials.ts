// Turn "Ada Admin" into "AA" for avatar circles. Shared by the sidebar,
// top bar and phone navigation.
export function initialsOf(name?: string | null): string {
  if (!name) return "?";
  return name
    .trim()
    .split(/\s+/)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");
}
